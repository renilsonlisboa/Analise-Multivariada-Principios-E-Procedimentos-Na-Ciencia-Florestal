% ORDENAÇÃO DAS DISTÂNCIAS GENERALIZADAS CALCULADAS NO EXEMPLO 3.1
D2JORD = sort(D2J);

% OBTENÇÃO DO VETOR DE POSIÇÕES (j)
POS = [1:1:n]';

% VALORES DE ALFA PARA CADA POSIÇÃO (j)
ALFA = (POS-0.5)/n;

% VALORES DE QUI-QUADRADO PARA CADA POSIÇÃO (j)
y = chi2inv(ALFA,p);

% AJUSTE DA EQUAÇÃO DA RETA PARA O GRÁFICO
coef = polyfit(D2JORD,y,1);

b0 = coef(2);
b1 = coef(1);

% ESTIMATIVAS DOS VALORES DA RETA PARA O GRÁFICO
ybest = b0+b1*D2JORD;

% GRÁFICO PARA AVALIAÇÃO DA NORMALIDADE p VARIADA
plot(D2JORD,y,D2JORD,ybest);
xlabel('DISTÂNCIA GENERALIZADA');
ylabel('VALOR DE QUI QUADRADO');
title('AVALIAÇÃO DA NORMALIDADE p VARIADA');
ylabel('VALOR DE QUI-QUADRADO');