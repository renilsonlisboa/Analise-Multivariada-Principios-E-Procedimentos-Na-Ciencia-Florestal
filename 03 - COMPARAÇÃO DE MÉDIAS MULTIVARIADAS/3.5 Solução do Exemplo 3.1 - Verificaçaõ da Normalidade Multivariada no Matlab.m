% SOLUÇÃO DO EXEMPLO 3.1 NO MATLAB

% VARIÁVEIS DAP E ALTURA
X = [
 19.5800 19.7000
 7.4800 14.9000
 16.0700 18.2000
 9.2300 15.7000
 9.3900 11.8000
 5.4100 12.0000
 8.4400 12.0000
 10.1900 18.5000
 18.9400 18.8000
 23.5500 21.7000
];

% MÉDIA
MEDIA = mean(X);

% MATRIZ VARIÂNCIA-COVARIÂNCIA
S = cov(X);

% INVERSA DA MATRIZ VARIÂNCIA-COVARIÂNCIA
INVS = inv(S);

% CÁLCULOS DAS DISTÂNCIAS GENERALIZADAS
D2J = sum((((X-MEDIA)*INVS).*(X-MEDIA)),2);

% TAMANHO DA AMOSTRA (n) E NÚMERO DE VARIÁVEIS (p)
[n,p] = size(X);

% OBTENÇÃO DO VALOR DE QUI-QUADRADO TABELADO
VALORTABELADO = chi2inv(0.5,p);

% NÚMERO DE VALORES MENORES OU IGUAIS AO VALOR DE QUI-QUADRADO TABELADO
PROPORCAOMENOR = nnz(D2J(:,:) <= VALORTABELADO);