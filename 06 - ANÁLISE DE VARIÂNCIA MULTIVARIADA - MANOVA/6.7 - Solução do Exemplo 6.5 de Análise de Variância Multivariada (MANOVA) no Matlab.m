g = size(ng,1);

% VETORES DE MÉDIAS DOS GRUPOS
MEDIAX1 = mean(X1);
MEDIAX2 = mean(X2);
MEDIAX3 = mean(X3);
MEDIAX4 = mean(X4);

% MATRIZ DE MÉDIAS DOS GRUPOS
MEDIAS = [
    MEDIAX1
    MEDIAX2
    MEDIAX3
    MEDIAX4
];

% VETOR DE MÉDIAS GERAL
MEDIAGERAL = mean(X);

% MATRIZ DE DIFERENÇAS DAS MÉDIAS DOS GRUPOS E A MÉDIA GERAL
DIFMEDIA = MEDIAS-MEDIAGERAL;

% MATRIZ DE DIFERENÇAS DAS MÉDIAS CORRIGIDAS PELO TAMANHO DOS GRUPOS
DIFMEDIACOR = DIFMEDIA.*ng;

% MATRIZ DE SOMA DOS QUADRADOS DOS GRUPOS
B = DIFMEDIACOR'*DIFMEDIA;

% MATRIZES DE DIFERENÇAS DOS VALORES DE CADA GRUPO E SUA RESPECTIVA MÉDIA
DIFX1 = X1-MEDIAX1;
DIFX2 = X2-MEDIAX2;
DIFX3 = X3-MEDIAX3;
DIFX4 = X4-MEDIAX4;

% MATRIZ GERAL DOS DESVIOS
DIF = [
    DIFX1
    DIFX2
    DIFX3
    DIFX4
];

% MATRIZ DE SOMAS DE QUADRADOS DOS RESÍDUOS
W = DIF'*DIF;

% CÁLCULO DO VALOR DE LAMBDA DE WILKS
L = det(W)/det(B+W);

% CÁLCULO DO VALOR DE LAMBDA DE WILKS CORRIGIDO
LCORRIGIDO = -(n-1-((p+g)/2))*log(L);

% VALOR CRÍTICO DE QUI-QUADRADO
QUI2 = chi2inv(0.99,p*(g-1));

% CÁLCULO DA ESTATÍSTICA DE PILLAI
PILLAI = trace(B*inv(B+W));

% CÁLCULO DA ESTATÍSTICA DE HOTELLING
HOTELLING = trace(inv(W)*B);

% CÁLCULO DA ESTATÍSTICA DE ROY
INVWB = inv(W)*B;

[VETOR,VALOR] = eig(INVWB);

[VALORAC,IND] = sort(diag(VALOR),'descend');

ROY = VALORAC(1)/(1+VALORAC(1));


