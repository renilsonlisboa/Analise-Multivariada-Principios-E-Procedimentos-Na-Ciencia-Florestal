% VETOR DE MÉDIAS
MEDIA = mean(X);

% VETOR DE DESVIOS PADRÃO
DESVIO = sqrt(var(X));

% PADRONIZAÇÃO DOS DADOS ORIGINAIS
[LINHA,COLUNA] = size(X);

for j = 1:COLUNA
    for i = 1:LINHA
        Z(i,j) = (X(i,j)-MEDIA(j))/DESVIO(j);
    end
end

% MATRIZ DE CORRELAÇÃO DOS DADOS ORIGINAIS
R = corr(X);

% INVERSA DA MATRIZ DE CORRELAÇÃO R
RINV = inv(R);

% MATRIZ RECÍPROCA DA INVERSA RINV
REC = RINV.^-1;

% DIAGONAL DA RECÍPROCA DA INVERSA
D = diag(diag(REC));

B = RINV*D;

II = eye(COLUNA);

% MATRIZ MODIFICADA DE PESOS – MATRIZ A
A = II-B;

% MATRIZ COMUM
CC = Z*A;

% MATRIZ VARIÂNCIA-COVARIÂNCIA DA MATRIZ COMUM
VARCOV_CC = cov(CC);

% MATRIZ DE CORRELAÇÃO DA MATRIZ COMUM
R_CC = corr(CC);

% AUTOVALORES E AUTOVETORES DA MATRIZ DE CORRELAÇÃO DA MATRIZ COMUM
[VETOR,VALOR] = eig(R_CC);

% AUTOVALORES ORDENADOS
[VALOR,IND] = sort(diag(VALOR));

VALOR = VALOR(end:-1:1);

% AUTOVETORES ORDENADOS POR AUTOVALORES – MATRIZ MODAL
INDICE = IND(end:-1:1);
MODAL = VETOR(:,INDICE);

% AUTOVALORES ACUMULADOS
AVA = cumsum(VALOR);

% VARIÂNCIA EXPLICADA ACUMULADA PELOS FATORES
VE = AVA/trace(R_CC);

% MATRIZ DE DADOS TRANSFORMADOS
Y = CC*MODAL;

% MATRIZ VARIÂNCIA-COVARIÂNCIA DA MATRIZ DE DADOS TRANSFORMADOS - Y
VARCOV_Y = cov(Y);

% MATRIZ DE CORRELAÇÃO DA MATRIZ DE DADOS TRANSFORMADOS - Y
R_Y = corr(Y);

% RAIZ QUADRADA DOS AUTOVALORES
RAIZVALOR = VALOR.^0.5;

% CÁLCULO DOS CARREGAMENTOS – LOADINGS
n = length(RAIZVALOR);

for i = 1:n
    for j = 1:n
        LOADINGS(j,i) = MODAL(j,i)*RAIZVALOR(i);
    end
end