% DIMENSÕES DA MATRIZ DE LOADINGS
[NV,NF] = size(X);

% DEFINIÇÃO DAS MATRIZES
c = X;
XT = X';

% INÍCIO DO LOOP ITERATIVO
ITER = 0;

% INICIALIZAÇÃO DA MATRIZ DE ROTAÇÃO (T)
T = eye(NF);

% NÚMERO MÁXIMO DE ITERAÇÕES
NMI = 200;

% INÍCIO DO PROCESSO ITERATIVO
while ITER < NMI

    % LOADINGS ATUAIS ROTACIONADOS
    LR = X*T;

    % POTÊNCIA CÚBICA (MAXIMIZA A VARIÂNCIA DOS QUADRADOS DOS LOADINGS)
    PC = LR.^3;
    PC = real(PC);
    c5 = LR;

    % MATRIZ DIAGONAL F
    F = (1/NV)*diag(diag(LR'*LR));
    F = real(F);

    % MATRIZ GR (GRADIENTE DA ROTAÇÃO)
    GR = XT*(PC-LR*F);
    GR = real(GR);

    % ATUALIZAÇÃO DA MATRIZ DE ROTAÇÃO
    T = (inv(sqrtm(GR*GR')))*GR;
    T = real(T);

    % ATUALIZAÇÃO DO CONTADOR
    ITER = ITER + 1;
end

